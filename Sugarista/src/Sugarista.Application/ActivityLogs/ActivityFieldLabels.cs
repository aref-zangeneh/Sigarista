    public static bool ShouldSkip(string key) => IgnoredKeys.Contains(key);

    public static string LabelFor(string key)
    {
        if (Labels.TryGetValue(key, out var label))
        {
            return label;
        }

        // camelCase → «first name» so unknown fields still read kindly
        var humanized = key switch
        {
            null or "" => "فیلد",
            _ => key[..1].ToLowerInvariant() + key[1..],
        };

        return humanized.Length <= 40 ? humanized : humanized[..40];
    }
